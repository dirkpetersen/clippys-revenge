    [Fact]
    public void CleanMeetingPhrasing_cases()
    {
        var def = StyleSkillText.DefaultMeetingPhrasing;
        Assert.Equal(def, StyleSkillText.CleanMeetingPhrasing(null));
        Assert.Equal(def, StyleSkillText.CleanMeetingPhrasing(""));
        Assert.Equal(def, StyleSkillText.CleanMeetingPhrasing("   "));
        Assert.Equal(def, StyleSkillText.CleanMeetingPhrasing("<!---->"));
        Assert.Equal("Would any of these work? Let me know.", StyleSkillText.CleanMeetingPhrasing("Would any of\r\nthese work?\tLet me know."));
        Assert.Equal("Mail <email>", StyleSkillText.CleanMeetingPhrasing("Mail ann@other.org"));
        Assert.Equal("x ok", StyleSkillText.CleanMeetingPhrasing("<!-- x --> ok"));
        var nested = StyleSkillText.CleanMeetingPhrasing("<<!--!-- hi -->>");
        Assert.DoesNotContain("<!--", nested);
        Assert.DoesNotContain("-->", nested);
        Assert.Contains("hi", nested);
        Assert.Equal(new string('a', 600), StyleSkillText.CleanMeetingPhrasing(new string('a', 600)));
        Assert.Equal(def, StyleSkillText.CleanMeetingPhrasing(new string('a', 601)));
        Assert.Equal("a b", StyleSkillText.CleanMeetingPhrasing("a" + new string(' ', 700) + "b"));
        foreach (var raw in new[] { "Would any of\r\nthese work?", "Mail ann@other.org", "<!-- x --> ok", "<<!--!-- hi -->>", "a <!-- b -->  c", def })
        {
            var o = StyleSkillText.CleanMeetingPhrasing(raw);
            Assert.Equal(o, StyleSkillText.CleanMeetingPhrasing(o));
        }
    }

    [Fact]
    public void ReadMeetingPhrasing_cases()
    {
        Assert.Equal("Hi", StyleSkillText.ReadMeetingPhrasing(Json("{\"body_markdown\":\"x\",\"meeting_phrasing\":\"Hi\"}")));
        Assert.Null(StyleSkillText.ReadMeetingPhrasing(Json("{\"body_markdown\":\"x\"}")));
        Assert.Null(StyleSkillText.ReadMeetingPhrasing(Json("{\"meeting_phrasing\":5}")));
        Assert.Null(StyleSkillText.ReadMeetingPhrasing(Json("5")));
        Assert.Null(StyleSkillText.ReadMeetingPhrasing(Json("[]")));
        Assert.Null(StyleSkillText.ReadMeetingPhrasing(default));
    }

    [Fact]
    public void RemoveMeetingSections_cases()
    {
        Assert.Equal("BODY\n\nMY NOTE", StyleSkillText.RemoveMeetingSections("BODY\n\n" + Sec("D", null) + "MY NOTE"));
        Assert.Equal("A\n\nBETWEEN\n\nC", StyleSkillText.RemoveMeetingSections("A\n\n" + Sec("D", null) + "BETWEEN\n\n" + Sec("D", "x") + "C"));
        var open = "A\n<!-- clippy:meeting-times v1 -->\nB";
        Assert.Equal(open, StyleSkillText.RemoveMeetingSections(open));
        Assert.Equal("A\n\nB", StyleSkillText.RemoveMeetingSections("A\n\n  <!-- clippy:meeting-times v0 -->\nold\n  <!-- /clippy:meeting-times -->\nB"));
        Assert.Equal("A\n\nB", StyleSkillText.RemoveMeetingSections(("A\n\n" + Sec("D", null) + "B").Replace("\n", "\r\n")));
        var endOnly = "A\n<!-- /clippy:meeting-times -->\nB";
        Assert.Equal(endOnly, StyleSkillText.RemoveMeetingSections(endOnly));
        Assert.Equal("", StyleSkillText.RemoveMeetingSections(null!));
    }

    [Fact]
    public void StripHeader_returns_the_body_of_a_rendered_file()
